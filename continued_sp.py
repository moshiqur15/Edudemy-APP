if 'df' in locals(): # Check if df was loaded successfully
    drop_cols = ['Dalc','Walc']  # alcohol consumption
    df = df.drop(columns=drop_cols)

    # -------------------------------
    # 3. Encode Categorical Variables
    # -------------------------------
    for col in df.columns:
        if df[col].dtype == 'object':
            le = LabelEncoder()
            df[col] = le.fit_transform(df[col])

    # -------------------------------
    # 4. Feature Mapping → 6 Dimensions
    # -------------------------------
    def compute_dimensions(row):
        # Academic: grades + studytime
        academic = np.mean([row['G1'], row['G2'], row['G3']]) * 5  # scale to ~100
        academic += row['studytime'] * 10

        # Engagement: inverse absences + supports
        engagement = (100 - min(row['absences'], 100))  # cap absences
        engagement += row['schoolsup'] * 20 + row['famsup'] * 10

        # Behavior/Social: social/freetime/famrel
        behavior = np.mean([row['goout'], row['freetime'], row['famrel']]) * 20

        # Extracurricular: activities + paid classes
        extracurricular = row['activities'] * 50 + row['paid'] * 30

        # Well-being: health + (inverse absences)
        wellbeing = row['health'] * 20 + (100 - min(row['absences'], 100))

        # Family support: famsup + schoolsup
        familysupport = row['famsup'] * 30 + row['schoolsup'] * 20

        return pd.Series([academic, engagement, behavior, extracurricular, wellbeing, familysupport])

    df[['Academic', 'Engagement', 'Behavior', 'Extracurricular', 'Well-being', 'Family Support']] = df.apply(compute_dimensions, axis=1)

    # -------------------------------
    # 5. Scale Features
    # -------------------------------
    scaler = MinMaxScaler()
    scaled_features = scaler.fit_transform(df[['Academic', 'Engagement', 'Behavior', 'Extracurricular', 'Well-being', 'Family Support']])
    scaled_df = pd.DataFrame(scaled_features, columns=['Academic', 'Engagement', 'Behavior', 'Extracurricular', 'Well-being', 'Family Support'])

    # -------------------------------
    # 6. Determine Optimal Clusters (Elbow Method)
    # -------------------------------
    inertia = []
    K_range = range(1, 11)
    for k in K_range:
        kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
        kmeans.fit(scaled_df)
        inertia.append(kmeans.inertia_)

    plt.figure(figsize=(8, 5))
    plt.plot(K_range, inertia, marker='o')
    plt.title('Elbow Method for Optimal k')
    plt.xlabel('Number of Clusters (k)')
    plt.ylabel('Inertia')
    plt.xticks(K_range)
    plt.grid(True)
    plt.show()

    # 7. Apply K-Means Clustering
    # -------------------------------
